function pe(machine = 0x8664) {
    const value = Buffer.alloc(88);
    value.write("MZ", 0, "ascii");
    value.writeUInt32LE(64, 60);
    value.write("PE\0\0", 64, "binary");
    value.writeUInt16LE(machine, 68);
    return value;
}

function peX64() {
    return pe(0x8664);
}

function makeBundle({ manifestArchitecture = "x64", bootstrapMachine = 0x8664 } = {}) {
    const plugin = mkdtempSync(path.join(tmpdir(), "offeragent-installer-"));
    const previousLocalAppData = process.env.LOCALAPPDATA;
    process.env.LOCALAPPDATA = path.join(plugin, "localappdata");
    mkdirSync(process.env.LOCALAPPDATA, { recursive: true });
    const root = path.join(plugin, "runtime");
    const platformRoot = path.join(root, "windows-x64");
    mkdirSync(platformRoot, { recursive: true });
    const helper = pe(bootstrapMachine);
    const files = [
        ["LICENSES/a", "license", false],
        ["offeragent-host.exe", "executable", true],
        ["offeragent-process-host.exe", "executable", true],
        ["offeragent-self-test.exe", "executable", true],
        ["offeragent-worker.exe", "executable", true],
        ["process-catalog.v1.json", "asset", false],
        ["provenance/a", "provenance", false],
        ["sbom/a", "sbom", false],
        ["web/index.html", "web", false],
    ].map(([filePath, kind, authenticode]) => ({
        path: filePath,
        byteLength: filePath === "process-catalog.v1.json" ? 1876 : 1,
        sha256: filePath === "process-catalog.v1.json"
            ? PRIVILEGE_ENVELOPE.processCatalogSha256 : digest(Buffer.from(filePath)),
        kind,
        authenticode,
    }));
    const contentDigest = digest(Buffer.from(JSON.stringify(
        files.map(({ path: filePath, byteLength, sha256 }) => ({ byteLength, path: filePath, sha256 })),
    )));
    const manifest = {
        schemaVersion: 2,
        runtimeVersion: "2.0.0",
        coreVersion: "2.0.0",
        pluginMinimumVersion: "2.0.0",
        pluginMaximumVersion: "2.9.9",
        signingKeyId: "release-2026",
        buildCommit: "a".repeat(40),
        createdAt: "2026-07-13T00:00:00Z",
        platform: { os: "windows", architecture: manifestArchitecture, minimumWindowsBuild: 19045 },
        protocol: { minimum: "1.0", maximum: "1.1", schemaHash: `sha256:${"b".repeat(64)}` },
        stateSchemaVersion: 1,
        toolAbiVersion: "1",
        archive: { fileName: "offeragent-runtime.zip", contentDigest, maximumExpandedBytes: 1024 * 1024 },
        bootstrap: {
            path: "offeragent-bootstrap.exe",
            byteLength: helper.length,
            sha256: digest(helper),
            authenticode: true,
            dependencies: [],
        },
        files,
        capabilities: ["offline", "safe_update"],
        privilegeEnvelope: PRIVILEGE_ENVELOPE,
    };
    const manifestBytes = canonical(manifest);
    const { privateKey, publicKey } = generateKeyPairSync("ed25519");
    const signature = Buffer.from(`${base64url(sign(null, manifestBytes, privateKey))}\n`, "ascii");
    const publicDer = publicKey.export({ type: "spki", format: "der" });
    writeFileSync(path.join(platformRoot, "runtime-manifest.json"), manifestBytes);
    writeFileSync(path.join(platformRoot, "runtime-manifest.sig"), signature);
    writeFileSync(path.join(platformRoot, "offeragent-bootstrap.exe"), helper);
    writeFileSync(path.join(platformRoot, "offeragent-runtime.zip"), "zip");
    return {
        plugin,
        root,
        platformRoot,
        manifest,
        manifestBytes,
        privateKey,
        publicKey: base64url(publicDer.subarray(-32)),
        cleanup: () => {
            if (previousLocalAppData === undefined) delete process.env.LOCALAPPDATA;
            else process.env.LOCALAPPDATA = previousLocalAppData;
            rmSync(plugin, { recursive: true, force: true });
        },
    };
}

function fakeBootstrap(bundle, invocations) {
    return (executable, args, options) => {
        const child = new EventEmitter();
        const stderr = new PassThrough();
        const request = new PassThrough();
        const result = new PassThrough();
        child.stdio = [null, null, stderr, request, result];
        child.kill = () => {};
        const invocation = { executable, args, options, request: null };
        invocations.push(invocation);
        const chunks = [];
        request.on("data", (chunk) => chunks.push(Buffer.from(chunk)));
        request.on("end", () => {
            const install = JSON.parse(Buffer.concat(chunks).toString("utf8"));
            invocation.request = install;
            assert.equal(install.bundleRoot, bundle.platformRoot);
            assert.equal(args.includes(bundle.platformRoot), false);
            const manifestHash = digest(bundle.manifestBytes);
            result.write(canonical({ phase: "extracting_to_staging", type: "progress" }));
            result.write(canonical({ phase: "verifying_each_file", type: "progress" }));
            result.write(canonical({ phase: "atomic_activate", type: "progress" }));
            result.write(canonical({ phase: "runtime_self_test", type: "progress" }));
            result.write(canonical({
                bootstrapAuthenticode: true,
                hostExecutable: path.join(
                    process.env.LOCALAPPDATA, "OfferAgent", "runtime", bundle.manifest.runtimeVersion,
                    "offeragent-host.exe",
                ),
                manifestHash,
                protocolMaximum: "1.1",
                protocolMinimum: "1.0",
                privilegeFingerprint: bundle.manifest.privilegeEnvelope.fingerprint,
                runtimeVersion: bundle.manifest.runtimeVersion,
                schemaHash: `sha256:${"b".repeat(64)}`,
                status: "ready",
                type: "result",
            }));
            result.end();
            setImmediate(() => child.emit("exit", 0));
        });
        return child;
    };
}

function installCurrent(bundle, catalogPayload, installed = null) {
    const current = installed ?? {
        manifest: bundle.manifest,
        manifestBytes: bundle.manifestBytes,
        signature: readFileSync(path.join(bundle.platformRoot, "runtime-manifest.sig")),
    };
    const runtimeRoot = path.join(process.env.LOCALAPPDATA, "OfferAgent", "runtime");
    const currentRoot = path.join(runtimeRoot, current.manifest.runtimeVersion);
    mkdirSync(currentRoot, { recursive: true });
    writeFileSync(path.join(currentRoot, "runtime-manifest.json"), current.manifestBytes);
    writeFileSync(path.join(currentRoot, "runtime-manifest.sig"), current.signature);
    writeFileSync(path.join(currentRoot, "process-catalog.v1.json"), catalogPayload);
    writeFileSync(path.join(runtimeRoot, "current.json"), canonical({
        activatedAt: "2026-07-13T00:00:00.000Z",
        currentVersion: current.manifest.runtimeVersion,
        generation: 1,
        manifestHash: digest(current.manifestBytes),
        previousVersion: null,
        privilegeApprovalJournal: [],
        rollbackSnapshot: null,
        stateSchemaVersion: current.manifest.stateSchemaVersion,
    }));
}

function expandedRelease(bundle, productionCatalog, runtimeVersion) {
    const catalogDocument = JSON.parse(productionCatalog.toString("utf8"));
    catalogDocument.environmentProfiles[0].allowedNames = ["OFFERAGENT_SAFE"];
    const catalog = canonical(catalogDocument);
    assert.equal(digest(catalog), "sha256:9085dab6573d8dccc6f7bca20c652b4c896998f43358dd5d98b62aa014cb65a9");
    const manifest = JSON.parse(JSON.stringify(bundle.manifest));
    manifest.runtimeVersion = runtimeVersion;
    manifest.coreVersion = runtimeVersion;
    const catalogRecord = manifest.files.find((item) => item.path === "process-catalog.v1.json");
    catalogRecord.byteLength = catalog.length;
    catalogRecord.sha256 = digest(catalog);
    manifest.archive.contentDigest = digest(Buffer.from(JSON.stringify(
        manifest.files.map(({ path: filePath, byteLength, sha256 }) => ({ byteLength, path: filePath, sha256 })),
    )));
    const envelope = manifest.privilegeEnvelope;
    envelope.processCatalogSha256 = digest(catalog);
    envelope.environmentProfiles[0].allowedNames = ["OFFERAGENT_SAFE"];
    const profileFingerprints = {
        "hook:hook-continue": "sha256:527710fbeb1dd2de179a51147e52070c042b89e2668444a9e8ac6b41453f8427",
        "shell:runtime-info": "sha256:1cf5be0a7803656bd2183a6d1b2d29c951fd7d4c11c93a5769463f97a3942f59",
    };
    for (const profile of envelope.profilePrivileges) {
        profile.allowedPlainEnvironmentNames = ["OFFERAGENT_SAFE"];
        profile.privilegeFingerprint = profileFingerprints[`${profile.kind}:${profile.profileId}`];
    }
    envelope.fingerprint = "sha256:0f5534c341898d3d25afc8e286e11713677191ef1fc8521d175b123ea103d18f";
    const manifestBytes = canonical(manifest);
    const signature = Buffer.from(`${base64url(sign(null, manifestBytes, bundle.privateKey))}\n`, "ascii");
    return { catalog, manifest, manifestBytes, signature };
}

