test("privilege approval receives the installer AbortSignal and releases startup on unload", async () => {
    const { EmbeddedRuntimeInstaller } = loadModule();
    const bundle = makeBundle();
    const controller = new AbortController();
    let enteredApproval;
    const approvalEntered = new Promise((resolve) => { enteredApproval = resolve; });
    let spawned = false;
    try {
        const installer = new EmbeddedRuntimeInstaller({
            pluginDirectory: bundle.plugin,
            vaultRoot: bundle.plugin,
            pluginVersion: "2.0.0-beta.28",
            protocolVersion: "1.0",
            schemaHash: `sha256:${"b".repeat(64)}`,
            releasePublicKeys: { "release-2026": bundle.publicKey },
            approvePrivilegeExpansion: async (_request, signal) => {
                assert.equal(signal, controller.signal);
                enteredApproval();
                return await new Promise((resolve) => signal.addEventListener("abort", () => resolve(false), {
                    once: true,
                }));
            },
            spawnProcess: () => { spawned = true; throw new Error("must not run"); },
        });
        const startup = installer.ensureReady(controller.signal, () => {});
        await approvalEntered;
        controller.abort();
        await assert.rejects(startup, (error) => error?.name === "AbortError");
        assert.equal(spawned, false);
    } finally {
        bundle.cleanup();
    }
});

