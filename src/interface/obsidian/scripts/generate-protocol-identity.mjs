import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const manifestPath = join(root, "..", "..", "..", "packages", "offeragent-harness", "schema", "protocol-manifest.json");
const outputPath = join(root, "src", "runtime", "generated_protocol_identity.ts");
const raw = await readFile(manifestPath, "utf8");
const manifest = JSON.parse(raw);
const exact = ["examples", "files", "generatorVersion", "manifestVersion", "protocolVersion", "schemaBundle", "schemaHash", "schemaVersion"];
if (!manifest || typeof manifest !== "object" || Array.isArray(manifest) ||
    Object.keys(manifest).length !== exact.length || exact.some((key) => !(key in manifest)) ||
    manifest.manifestVersion !== 1 || manifest.generatorVersion !== "1" ||
    !/^\d+\.\d+$/.test(manifest.protocolVersion) || !/^\d+$/.test(manifest.schemaVersion) ||
    !/^sha256:[0-9a-f]{64}$/.test(manifest.schemaHash)) {
    throw new Error("OfferAgent protocol manifest is invalid");
}
const bundle = manifest.files[manifest.schemaBundle];
if (!bundle || bundle.sha256 !== manifest.schemaHash) throw new Error("protocol schema hash does not match bundle entry");
const source = `/* Generated by scripts/generate-protocol-identity.mjs; do not edit. */\n` +
    `export const PROTOCOL_VERSION = ${JSON.stringify(manifest.protocolVersion)};\n` +
    `export const PROTOCOL_SCHEMA_VERSION = ${JSON.stringify(manifest.schemaVersion)};\n` +
    `export const PROTOCOL_SCHEMA_HASH = ${JSON.stringify(manifest.schemaHash)};\n`;
await writeFile(outputPath, source, { encoding: "utf8" });
