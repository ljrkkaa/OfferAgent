import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const manifestPath = join(root, "..", "..", "..", "packages", "offeragent-harness", "schema", "protocol-manifest.json");
const defaultOutputPath = join(root, "src", "runtime", "generated_protocol_identity.ts");
const { check, outputPath } = parseArguments(defaultOutputPath);
const raw = await readFile(manifestPath, "utf8");
const manifest = JSON.parse(raw);
const exact = ["examples", "files", "generatorVersion", "manifestVersion", "protocolVersion", "schemaBundle", "schemaHash", "schemaVersion"];
if (!manifest || typeof manifest !== "object" || Array.isArray(manifest) ||
    Object.keys(manifest).length !== exact.length || exact.some((key) => !(key in manifest)) ||
    manifest.manifestVersion !== 1 || manifest.generatorVersion !== "1" ||
    !/^\d+\.\d+$/.test(manifest.protocolVersion) || !/^\d+$/.test(manifest.schemaVersion) ||
    !/^sha256:[0-9a-f]{64}$/.test(manifest.schemaHash)) {
    throw new Error("OfferAgent protocol manifest is invalid");
}
const bundle = manifest.files[manifest.schemaBundle];
if (!bundle || bundle.sha256 !== manifest.schemaHash) throw new Error("protocol schema hash does not match bundle entry");
const source = `/* Generated by scripts/generate-protocol-identity.mjs; do not edit. */\n` +
    `export const PROTOCOL_VERSION = ${JSON.stringify(manifest.protocolVersion)};\n` +
    `export const PROTOCOL_SCHEMA_VERSION = ${JSON.stringify(manifest.schemaVersion)};\n` +
    `export const PROTOCOL_SCHEMA_HASH = ${JSON.stringify(manifest.schemaHash)};\n`;
await writeOrCheck(outputPath, source, check);

function parseArguments(defaultOutput) {
    let check = false;
    let outputPath = defaultOutput;
    for (let index = 2; index < process.argv.length; index += 1) {
        const argument = process.argv[index];
        if (argument === "--check") {
            check = true;
            continue;
        }
        if (argument === "--output") {
            const value = process.argv[index + 1];
            if (!value || value.startsWith("--")) throw new Error("--output requires a file path");
            outputPath = value;
            index += 1;
            continue;
        }
        throw new Error(`unsupported argument: ${argument}`);
    }
    return { check, outputPath };
}

async function writeOrCheck(outputPath, source, check) {
    if (!check) {
        await writeFile(outputPath, source, { encoding: "utf8" });
        return;
    }
    let actual;
    try {
        actual = await readFile(outputPath, "utf8");
    } catch (error) {
        if (error?.code === "ENOENT") {
            throw new Error(`generated protocol identity is missing: ${outputPath}; run yarn protocol:generate`);
        }
        throw error;
    }
    if (actual !== source) {
        throw new Error(`generated protocol identity is stale: ${outputPath}; run yarn protocol:generate`);
    }
}
