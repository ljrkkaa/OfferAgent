import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const pluginRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const schemaRoot = join(pluginRoot, "..", "..", "..", "packages", "offeragent-harness", "schema");
const manifest = JSON.parse(await readFile(join(schemaRoot, "protocol-manifest.json"), "utf8"));
if (!manifest || typeof manifest !== "object" || Array.isArray(manifest) ||
    typeof manifest.schemaBundle !== "string" || !/^sha256:[0-9a-f]{64}$/.test(manifest.schemaHash)) {
    throw new Error("OfferAgent protocol manifest is invalid");
}
const schemaBytes = await readFile(join(schemaRoot, manifest.schemaBundle));
const digest = `sha256:${createHash("sha256").update(schemaBytes).digest("hex")}`;
if (digest !== manifest.schemaHash) throw new Error("OfferAgent protocol schema bytes do not match schemaHash");
const schema = JSON.parse(schemaBytes.toString("utf8"));
if (!schema || typeof schema !== "object" || Array.isArray(schema) || schema.protocolVersion !== manifest.protocolVersion ||
    schema.schemaVersion !== manifest.schemaVersion || !schema.$defs || typeof schema.$defs !== "object") {
    throw new Error("OfferAgent protocol schema root is invalid");
}

const definitions = schema.$defs;
const definitionNames = Object.keys(definitions).sort();
for (const name of definitionNames) {
    if (!/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name)) throw new Error(`invalid TypeScript schema name: ${name}`);
}

const lines = [
    "/* Generated by scripts/generate-protocol-types.mjs; do not edit. */",
    `export const PROTOCOL_TYPES_SCHEMA_HASH = ${JSON.stringify(manifest.schemaHash)};`,
    "",
];
for (const name of definitionNames) {
    lines.push(`export type ${name} = ${renderSchema(definitions[name], 0)};`, "");
}
emitMethodMap(lines, "ProtocolCommandMap", schema.commands, true);
emitMethodMap(lines, "ProtocolEventMap", schema.events, false);
emitEnvelopeMap(lines, schema.envelopes);
emitStringTuple(lines, "PROTOCOL_COMMAND_METHODS", Object.keys(schema.commands).sort());
emitStringTuple(lines, "PROTOCOL_EVENT_TYPES", Object.keys(schema.events).sort());
emitDefinitionEnumTuple(lines, "PROTOCOL_ERROR_CODES", definitions.ErrorCode, "string");
emitDefinitionEnumTuple(lines, "PROTOCOL_JSON_RPC_ERROR_CODES", definitions.JsonRpcErrorCode, "integer");
emitDefinitionPropertyConst(lines, "PROTOCOL_RPC_CANCEL_METHOD", definitions.RpcCancelNotification, "method");
emitDefinitionPropertyConst(lines, "PROTOCOL_EVENT_NOTIFICATION_METHOD", definitions.EventNotification, "method");
lines.push(
    "export type ProtocolCommandMethod = keyof ProtocolCommandMap;",
    "export type ProtocolCommandParams<Method extends ProtocolCommandMethod> = ProtocolCommandMap[Method][\"params\"];",
    "export type ProtocolCommandResult<Method extends ProtocolCommandMethod> = ProtocolCommandMap[Method][\"result\"];",
    "export type ProtocolEventType = keyof ProtocolEventMap;",
    "export type ProtocolEventPayload<Type extends ProtocolEventType> = ProtocolEventMap[Type][\"payload\"];",
    "",
);
await writeFile(join(pluginRoot, "src", "runtime", "generated_protocol.ts"), `${lines.join("\n").trimEnd()}\n`, "utf8");

function emitMethodMap(output, name, mapping, requestResponse) {
    if (!mapping || typeof mapping !== "object" || Array.isArray(mapping)) throw new Error(`${name} is invalid`);
    output.push(`export interface ${name} {`);
    for (const method of Object.keys(mapping).sort()) {
        const value = mapping[method];
        if (!value || typeof value !== "object" || Array.isArray(value)) throw new Error(`${name}.${method} is invalid`);
        const expected = requestResponse ? ["params", "requiredCapability", "result"] : ["payload"];
        for (const key of Object.keys(value)) {
            if (!expected.includes(key)) throw new Error(`${name}.${method} contains unsupported metadata: ${key}`);
        }
        if (requestResponse) {
            if (!("params" in value) || !("result" in value)) throw new Error(`${name}.${method} is incomplete`);
            const capability = "requiredCapability" in value ? literal(value.requiredCapability) : "null";
            output.push(`  readonly ${JSON.stringify(method)}: {`);
            output.push(`    readonly \"params\": ${renderSchema(value.params, 2)};`);
            output.push(`    readonly \"result\": ${renderSchema(value.result, 2)};`);
            output.push(`    readonly \"requiredCapability\": ${capability};`);
            output.push("  };");
        } else {
            if (!("payload" in value)) throw new Error(`${name}.${method} is incomplete`);
            output.push(`  readonly ${JSON.stringify(method)}: { readonly \"payload\": ${renderSchema(value.payload, 1)}; };`);
        }
    }
    output.push("}", "");
}

function emitEnvelopeMap(output, mapping) {
    if (!mapping || typeof mapping !== "object" || Array.isArray(mapping)) throw new Error("envelopes are invalid");
    output.push("export interface ProtocolEnvelopeMap {");
    for (const name of Object.keys(mapping).sort()) {
        output.push(`  readonly ${JSON.stringify(name)}: ${renderSchema(mapping[name], 1)};`);
    }
    output.push("}", "");
}

function emitStringTuple(output, name, values) {
    if (!Array.isArray(values) || values.length === 0 || new Set(values).size !== values.length ||
        values.some((value) => typeof value !== "string" || value.length === 0)) {
        throw new Error(`${name} is invalid`);
    }
    output.push(`export const ${name} = Object.freeze(${JSON.stringify(values)} as const);`, "");
}

function emitDefinitionEnumTuple(output, name, definition, scalarType) {
    if (!definition || typeof definition !== "object" || Array.isArray(definition) ||
        definition.type !== scalarType || !Array.isArray(definition.enum) || definition.enum.length === 0) {
        throw new Error(`${name} schema enum is invalid`);
    }
    const valid = scalarType === "string"
        ? (value) => typeof value === "string" && value.length > 0
        : (value) => typeof value === "number" && Number.isSafeInteger(value);
    if (definition.enum.some((value) => !valid(value)) || new Set(definition.enum).size !== definition.enum.length) {
        throw new Error(`${name} schema enum values are invalid`);
    }
    output.push(`export const ${name} = Object.freeze(${JSON.stringify(definition.enum)} as const);`, "");
}

function emitDefinitionPropertyConst(output, name, definition, propertyName) {
    const property = definition?.properties?.[propertyName];
    if (!property || typeof property !== "object" || Array.isArray(property) ||
        typeof property.const !== "string" || property.const.length === 0) {
        throw new Error(`${name} schema const is invalid`);
    }
    output.push(`export const ${name} = ${JSON.stringify(property.const)} as const;`, "");
}

function renderSchema(node, depth) {
    if (node === true) return "unknown";
    if (node === false) return "never";
    if (!node || typeof node !== "object" || Array.isArray(node)) throw new Error("schema node is invalid");
    validateKeywords(node);
    if ("$ref" in node) return reference(node.$ref);
    if ("const" in node) return literal(node.const);
    if ("enum" in node) {
        if (!Array.isArray(node.enum) || node.enum.length === 0) return "never";
        return unique(node.enum.map(literal)).join(" | ");
    }
    const variants = node.anyOf ?? node.oneOf;
    if (variants !== undefined) {
        if (!Array.isArray(variants) || variants.length === 0) throw new Error("schema union is empty");
        return unique(variants.map((item) => renderSchema(item, depth))).join(" | ");
    }
    if (Array.isArray(node.type)) {
        if (node.type.length === 0) return "never";
        return unique(node.type.map((type) => renderType(node, type, depth))).join(" | ");
    }
    if (typeof node.type === "string") return renderType(node, node.type, depth);
    if (node.properties || "additionalProperties" in node) return renderObject(node, depth);
    if (node.items) return `ReadonlyArray<${renderSchema(node.items, depth + 1)}>`;
    return "unknown";
}

function renderType(node, type, depth) {
    if (type === "null") return "null";
    if (type === "boolean") return "boolean";
    if (type === "integer" || type === "number") return "number";
    if (type === "string") return "string";
    if (type === "array") return `ReadonlyArray<${node.items ? renderSchema(node.items, depth + 1) : "unknown"}>`;
    if (type === "object") return renderObject(node, depth);
    throw new Error(`unsupported JSON Schema type: ${String(type)}`);
}

function renderObject(node, depth) {
    const properties = node.properties ?? {};
    if (!properties || typeof properties !== "object" || Array.isArray(properties)) {
        throw new Error("object properties are invalid");
    }
    const required = new Set(node.required ?? []);
    if (![...required].every((name) => typeof name === "string" && name in properties)) {
        throw new Error("object required fields are invalid");
    }
    const names = Object.keys(properties).sort();
    const indent = "  ".repeat(depth);
    const childIndent = "  ".repeat(depth + 1);
    const shape = names.length === 0
        ? "Readonly<Record<string, never>>"
        : `{\n${names.map((name) => `${childIndent}readonly ${JSON.stringify(name)}${required.has(name) ? "" : "?"}: ${renderSchema(properties[name], depth + 1)};`).join("\n")}\n${indent}}`;
    const additional = node.additionalProperties;
    if (additional === false) return shape;
    const values = additional === undefined || additional === true ? "unknown" : renderSchema(additional, depth + 1);
    if (names.length === 0) return `Readonly<Record<string, ${values}>>`;
    return `(${shape} & Readonly<Record<string, ${values}>>)`;
}

function reference(value) {
    if (typeof value !== "string" || !value.startsWith("#/$defs/")) throw new Error(`unsupported schema reference: ${value}`);
    const name = value.slice("#/$defs/".length).replaceAll("~1", "/").replaceAll("~0", "~");
    if (!(name in definitions) || !/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name)) {
        throw new Error(`unknown schema reference: ${value}`);
    }
    return name;
}

function literal(value) {
    if (value === null || typeof value === "string" || typeof value === "boolean" ||
        (typeof value === "number" && Number.isFinite(value))) return JSON.stringify(value);
    throw new Error("schema literal is not JSON scalar");
}

function unique(values) {
    return [...new Set(values)];
}

function validateKeywords(node) {
    const supported = new Set([
        "$ref", "additionalProperties", "anyOf", "const", "default", "deprecated", "description", "discriminator",
        "enum", "examples", "exclusiveMaximum", "exclusiveMinimum", "format", "items", "maxItems", "maxLength",
        "maxProperties", "maximum", "minItems", "minLength", "minProperties", "minimum", "multipleOf", "oneOf",
        "pattern", "properties", "propertyNames", "readOnly", "required", "title", "type", "uniqueItems", "writeOnly",
    ]);
    for (const key of Object.keys(node)) {
        if (!supported.has(key)) throw new Error(`unsupported JSON Schema keyword: ${key}`);
    }
}
